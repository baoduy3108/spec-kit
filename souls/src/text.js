export function t(key, params = {}) {
  const table = WORDS[current] || WORDS.vi;
  const raw = table[key] ?? WORDS.en[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_m, name) =>
    params[name] === undefined ? `{${name}}` : String(params[name]),
  );
}
