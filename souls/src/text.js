// Five languages. Nothing else in the game stores a sentence, so switching
// re-reads the whole screen, including the epitaph on the death card.

export const LANGS = ['vi', 'en', 'ja', 'ko', 'zh'];
export const LABEL = { vi: 'VI', en: 'EN', ja: '日本語', ko: '한국어', zh: '中文' };

let current = 'vi';

export function setLang(code) {
  current = LANGS.includes(code) ? code : 'vi';
  return current;
}
export const langNow = () => current;
export function nextLang() {
  return LANGS[(LANGS.indexOf(current) + 1) % LANGS.length];
}

